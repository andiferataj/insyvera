import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';

test('complete research, analytics, evidence, report and evaluation journey',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByRole('button',{name:'Create an account',exact:true}).click();
 await page.getByLabel('Your name',{exact:true}).fill('Demo Researcher');
 await page.getByLabel('Email address').fill('demo-'+Date.now()+'@example.test');
 await page.getByLabel('Password',{exact:true}).fill('Insyvera-Demo-2026!');
 await page.getByRole('button',{name:'Create your workspace',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Make sense of what matters.'})).toBeVisible();
 await page.getByRole('button',{name:'Explore demo sources',exact:true}).click();
 await expect(page.locator('.summary-number')).toContainText('07',{timeout:60000});
 await fs.mkdir('docs/screenshots',{recursive:true});
 await page.evaluate(()=>window.scrollTo(0,0)); await expect(page.locator('.toast')).toHaveCount(0,{timeout:7000}); await page.screenshot({animations:'disabled',path:'docs/screenshots/overview.png',fullPage:true});
 await page.getByRole('navigation').getByRole('button',{name:'Knowledge library'}).click();
 await expect(page.getByRole('button',{name:/^taxes_2026.xlsx/})).toBeVisible();
 await page.getByRole('button',{name:/^christmas_gifts.xlsx/}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.getByText('570',{exact:true})).toHaveCount(0);
 await expect(page.getByRole('columnheader',{name:'Recipient',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.evaluate(()=>window.scrollTo(0,0)); await expect(page.locator('.toast')).toHaveCount(0,{timeout:7000}); await page.screenshot({animations:'disabled',path:'docs/screenshots/library.png',fullPage:true});
 await page.getByRole('navigation').getByRole('button',{name:'Research',exact:true}).click();
 await page.getByRole('textbox',{name:'Research question'}).fill('Compare my tax records, identify mismatches, and analyze Christmas gift spending.');
 await page.getByRole('button',{name:'Start research',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Here’s what the evidence shows.'})).toBeVisible({timeout:60000});
 await expect(page.getByRole('heading',{name:'Where the numbers differ'})).toBeVisible();
 await expect(page.getByText('Gift spending: 570',{exact:true})).toBeVisible();
 await expect(page.getByText('Over budget: 70',{exact:true})).toBeVisible();
 await expect(page.locator('.js-plotly-plot').first()).toBeVisible({timeout:30000});
 await page.locator('.calculation-ref').first().click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.getByRole('columnheader',{name:'Amount',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Close dialog'}).click();
 const citation=page.locator('.supporting-sources button').first();
 await citation.click();await expect(page.getByRole('heading',{name:'Follow the evidence'})).toBeVisible();
 await expect(page.locator('.source-quote')).toBeVisible();
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.evaluate(()=>window.scrollTo(0,0)); await expect(page.locator('.toast')).toHaveCount(0,{timeout:7000}); await page.screenshot({animations:'disabled',path:'docs/screenshots/research.png',fullPage:true});
 await page.getByRole('button',{name:'Create a report from this research'}).click();
 await expect(page.locator('.report-paper')).toBeVisible();
 await page.getByRole('button',{name:'Edit report',exact:true}).click();
 await page.getByLabel('Report title',{exact:true}).fill('Verified synthetic investigation');
 const content=page.getByLabel('Markdown content');
 await content.fill((await content.inputValue())+'\nReviewed by the researcher.');
 await page.getByRole('button',{name:'Save new version'}).click();
 await expect(page.getByRole('heading',{name:'Verified synthetic investigation',exact:true})).toBeVisible();
 await expect(page.getByLabel('Report version')).toHaveValue('2');
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'PDF',exact:true}).click()]);
 const file=await download.path();expect((await fs.readFile(file!)).subarray(0,4).toString()).toBe('%PDF');
 await page.getByRole('navigation').getByRole('button',{name:'Analytics',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Let your data speak.'})).toBeVisible();
 const dataset=page.getByLabel('Dataset',{exact:true});
 await dataset.selectOption({label:(await dataset.locator('option').allTextContents()).find(v=>v.includes('christmas_gifts.xlsx'))!});
 await page.getByLabel('Numeric column',{exact:true}).selectOption('Amount');
 await page.getByLabel('Group by',{exact:true}).selectOption('Recipient');
 await page.getByRole('button',{name:'Run analysis',exact:true}).click();
 await expect(page.locator('.analysis-total strong')).toHaveText('570');
 await page.evaluate(()=>window.scrollTo(0,0)); await expect(page.locator('.toast')).toHaveCount(0,{timeout:7000}); await page.screenshot({animations:'disabled',path:'docs/screenshots/analytics.png',fullPage:true});
 await page.getByRole('navigation').getByRole('button',{name:'Evaluation lab'}).click();
 await page.getByRole('button',{name:'Run synthetic benchmark'}).click();
 await expect(page.getByText('5 / 5 passed',{exact:true})).toBeVisible({timeout:60000});
 await page.evaluate(()=>window.scrollTo(0,0)); await expect(page.locator('.toast')).toHaveCount(0,{timeout:7000}); await page.screenshot({animations:'disabled',path:'docs/screenshots/lab.png',fullPage:true});
 await page.getByRole('navigation').getByRole('button',{name:'Agent workspace'}).click();
 await page.getByLabel('Calculation expression').fill('(84000 - 18000) / 12');
 await page.getByRole('button',{name:'Calculate',exact:true}).click();
 await expect(page.locator('.calculator-result')).toHaveText('5500');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Open navigation'}).click();
 await page.getByRole('navigation').getByRole('button',{name:'Overview',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Make sense of what matters.'})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0)); await expect(page.locator('.toast')).toHaveCount(0,{timeout:7000}); await page.screenshot({animations:'disabled',path:'docs/screenshots/mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 expect(errors).toEqual([]);
});

